def case(
    id: str,
    category: str,
    source: str,
    *,
    disposition: list[str] | str,
    backends: list[str] | None = None,
    extra_observation: str | None = None,
    acceptable_processing_modes: list[str] | None = None,
    expected_kernel_matches: list[str] | None = None,
    forbidden_kernel_matches: list[str] | None = None,
    expected_delta_topics: list[str] | None = None,
    forbidden_conclusions: list[str] | None = None,
    coi: dict | None = None,
    title: str | None = None,
) -> dict:
    return {
        "id": id,
        "category": category,
        "title": title or id,
        "source": source.strip(),
        "extra_observation": extra_observation,
        "kernel_fixture": "mvp",
        "backends": backends or ["rule"],
        "expected": {
            "disposition": [disposition] if isinstance(disposition, str) else disposition,
            "acceptable_processing_modes": acceptable_processing_modes or [],
            "expected_kernel_matches": expected_kernel_matches or [],
            "forbidden_kernel_matches": forbidden_kernel_matches or [],
            "expected_delta_topics": expected_delta_topics or [],
            "forbidden_conclusions": forbidden_conclusions
            or ["the system is scripted", "refute the entire architecture"],
            "claim_observation_inference_constraints": coi or {},
        },
    }


